import subprocess
import json

def run_sql(sql):
    cmd = ["docker", "exec", "-i", "poolbuy-mysql-1", "mysql", "-uroot", "-popencart", "opencart"]
    res = subprocess.run(cmd, input=sql, capture_output=True, text=True)
    if res.returncode != 0:
        print("SQL Error:", res.stderr)
    return res.stdout

